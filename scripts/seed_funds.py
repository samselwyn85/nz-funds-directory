def slug(s):
    s = s.lower().replace("ā", "a").replace("ē", "e").replace("ī", "i").replace("ō", "o").replace("ū", "u")
    return re.sub(r"[^a-z0-9]+", "-", s).strip("-")


def main():
    funds = []
    for name, funder, ftype, sectors, regions, elig, how, amount, url, summary in ROWS:
        funds.append({
            "id": slug(name),
            "name": name,
            "funder": funder,
            "funderType": ftype,
            "sectors": sectors,
            "regions": regions,
            "eligible": elig,
            "howToApply": how,
            "amount": amount,
            "url": url,
            "summary": summary,
            "nextDeadline": None,      # filled by check_funds.py when a date is found
            "roundStatus": "unknown",  # open | closed | unknown, from page wording
            "lastChecked": None,
            "linkStatus": "unchecked", # ok | moved | broken | unchecked
            "verified": False,         # a person has confirmed details
        })
    out = pathlib.Path(__file__).resolve().parent.parent / "site" / "data" / "funds.json"
    out.write_text(json.dumps({"updated": None, "funds": funds}, indent=2, ensure_ascii=False))
    print(f"wrote {len(funds)} funds to {out}")


if __name__ == "__main__":
    main()
